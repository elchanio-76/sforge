import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { basename, join, relative, sep } from 'node:path';
import { MIN_ENGINE_VERSION } from './engine.js';
import type { IacSpec } from './spec.js';

/** Root of the generated workspaces inside a project. */
export const IAC_DIR = join('.sforge', 'iac');

/** `.sforge/iac/<target>/` of a project. */
export function workspaceDir(rootDir: string, name: string): string {
  return join(rootDir, IAC_DIR, name);
}

/** User-supplied HCL merged into a target's workspace (`infra/<target>/*.tf`). */
export function extraHclDir(rootDir: string, targetName: string): string {
  return join(rootDir, 'infra', targetName);
}

const GENERATED_NOTE =
  'Generated by staticforge; rewritten before every run. Add your own .tf files to infra/<target>/.';

/** Prefix of files copied from infra/<target>/, so they can be replaced on the next run. */
const EXTRA_PREFIX = 'infra_';

export interface WriteWorkspaceOptions {
  dir: string;
  spec: IacSpec;
  /** Copy the module into `modules/<name>/` instead of referencing the packaged copy. */
  vendor?: boolean;
  /** Directory of extra `.tf` / `.tf.json` files to merge into the workspace. */
  extraDir?: string;
}

function toPosix(path: string): string {
  return path.split(sep).join('/');
}

function writeJson(path: string, value: unknown): void {
  writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`);
}

/**
 * Write the root workspace for a spec:
 * - `main.tf.json`: required providers, provider configs, a module block that
 *   passes every input from a root variable, and the re-exported outputs;
 * - `backend.tf.json` (absent for local state);
 * - `terraform.tfvars.json`: the module inputs;
 * - `.gitignore`: keeps `.terraform/`, plans and local state out of git.
 * The `.terraform.lock.hcl` written by `init` is meant to be committed.
 *
 * @returns The files written, relative to the workspace.
 */
export function writeWorkspace(options: WriteWorkspaceOptions): string[] {
  const { dir, spec } = options;
  mkdirSync(dir, { recursive: true });
  const written: string[] = [];

  let source: string;
  const vendored = join(dir, 'modules', spec.module.name);
  rmSync(vendored, { recursive: true, force: true });
  if (options.vendor) {
    cpSync(spec.module.dir, vendored, {
      recursive: true,
      filter: (path) =>
        !/[\\/](\.terraform|tests)([\\/]|$)/.test(path.slice(spec.module.dir.length)),
    });
    source = `./modules/${spec.module.name}`;
  } else {
    const rel = toPosix(relative(dir, spec.module.dir));
    source = rel.startsWith('.') ? rel : `./${rel}`;
  }

  const inputs = Object.keys(spec.module.inputs).sort();
  const main = {
    '//': GENERATED_NOTE,
    terraform: {
      required_version: `>= ${MIN_ENGINE_VERSION}`,
      required_providers: spec.requiredProviders,
    },
    provider: spec.providers,
    variable: Object.fromEntries(inputs.map((name) => [name, {}])),
    module: {
      [spec.module.name]: {
        source,
        ...(spec.module.providers && { providers: spec.module.providers }),
        ...Object.fromEntries(inputs.map((name) => [name, `\${var.${name}}`])),
      },
    },
    ...(spec.outputs.length > 0 && {
      output: Object.fromEntries(
        spec.outputs.map((name) => [name, { value: `\${module.${spec.module.name}.${name}}` }]),
      ),
    }),
  };
  writeJson(join(dir, 'main.tf.json'), main);
  written.push('main.tf.json');

  const backendFile = join(dir, 'backend.tf.json');
  if (spec.backend.type === 'local') {
    rmSync(backendFile, { force: true });
  } else {
    writeJson(backendFile, {
      '//': GENERATED_NOTE,
      terraform: { backend: { [spec.backend.type]: spec.backend.config } },
    });
    written.push('backend.tf.json');
  }

  writeJson(join(dir, 'terraform.tfvars.json'), spec.module.inputs);
  written.push('terraform.tfvars.json');

  // Without vendoring, main.tf.json holds a path into node_modules that differs per machine.
  writeFileSync(
    join(dir, '.gitignore'),
    [
      `# ${GENERATED_NOTE}`,
      '/.terraform/',
      '/tfplan',
      '/terraform.tfstate',
      '/terraform.tfstate.*',
      ...(options.vendor ? [] : ['/main.tf.json']),
      '',
    ].join('\n'),
  );
  written.push('.gitignore');

  for (const name of readdirSync(dir)) {
    if (name.startsWith(EXTRA_PREFIX)) rmSync(join(dir, name), { force: true });
  }
  if (options.extraDir !== undefined && existsSync(options.extraDir)) {
    for (const name of readdirSync(options.extraDir).sort()) {
      const path = join(options.extraDir, name);
      if (!/\.tf(\.json)?$/.test(name) || !statSync(path).isFile()) continue;
      const copy = `${EXTRA_PREFIX}${basename(name)}`;
      cpSync(path, join(dir, copy));
      written.push(copy);
    }
  }
  return written;
}
