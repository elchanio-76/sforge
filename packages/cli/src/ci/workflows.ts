import { uses } from './actions.js';

/** A target as the workflows see it. */
export interface CiTarget {
  name: string;
  provider: 'aws' | 'azure';
  /** AWS region (for the STS endpoint). */
  region?: string;
  /** GitHub environment the production deploy runs in (approval rules are set in GitHub). */
  environment?: string;
  /** Branch whose pushes deploy production. */
  branch: string;
  /** Deploy pull requests as previews. */
  previews: boolean;
}

export interface WorkflowOptions {
  targets: CiTarget[];
  packageManager: 'pnpm' | 'npm';
  /** The project's directory relative to the repository root ('' for the root). */
  workingDirectory: string;
  /** `.nvmrc` (or similar) relative to the repository root; otherwise Node 24. */
  nodeVersionFile?: string;
  /** pnpm version for projects without a `packageManager` field. */
  pnpmVersion?: string;
  /** The Playwright version the checker uses: the Chromium download and its cache key. */
  playwrightVersion: string;
}

/** A repository variable the workflows read, and the provision output it holds. */
export interface RepoVariable {
  target: string;
  name: string;
  output: string;
}

/** A target name as an environment variable name part: `my-site` → `MY_SITE`. */
function upper(target: string): string {
  return target.toUpperCase().replace(/-/g, '_');
}

/** `SFORGE_<TARGET>_<SUFFIX>`: repository variable names are upper case. */
function variable(target: string, suffix: string): string {
  return `SFORGE_${upper(target)}_${suffix}`;
}

/** The repository variables a target's jobs need. They are identifiers, not secrets. */
export function variablesFor(target: CiTarget): RepoVariable[] {
  if (target.provider === 'aws') {
    return [
      { target: target.name, name: variable(target.name, 'ROLE_ARN'), output: 'ci_role_arn' },
    ];
  }
  return [
    { target: target.name, name: variable(target.name, 'CLIENT_ID'), output: 'ci_client_id' },
    { target: target.name, name: variable(target.name, 'TENANT_ID'), output: 'ci_tenant_id' },
    {
      target: target.name,
      name: variable(target.name, 'SUBSCRIPTION_ID'),
      output: 'ci_subscription_id',
    },
  ];
}

const HEADER =
  '# Generated by `sforge ci init`. Edit freely; run it again with --force to start over.\n';

/** Indent every line of a block. */
function indent(text: string, spaces: number): string {
  const pad = ' '.repeat(spaces);
  return text
    .split('\n')
    .map((line) => (line === '' ? line : pad + line))
    .join('\n');
}

/** Path of a project file relative to the repository root. */
function inProject(options: WorkflowOptions, path: string): string {
  return options.workingDirectory === '' ? path : `${options.workingDirectory}/${path}`;
}

function sforge(options: WorkflowOptions): string {
  return options.packageManager === 'pnpm' ? 'pnpm exec sforge' : 'npx sforge';
}

/** Checkout, Node, dependencies and sforge's download cache (OpenTofu and its providers). */
function setupSteps(options: WorkflowOptions, fetchDepth?: number): string {
  const node = options.nodeVersionFile
    ? `node-version-file: ${options.nodeVersionFile}`
    : 'node-version: 24';
  const lockfile = inProject(
    options,
    options.packageManager === 'pnpm' ? 'pnpm-lock.yaml' : 'package-lock.json',
  );
  const steps = [
    `- uses: ${uses('checkout')}`,
    ...(fetchDepth === undefined
      ? []
      : ['  with:', `    fetch-depth: ${fetchDepth} # rollbacks on Azure rebuild an older commit`]),
  ];
  if (options.packageManager === 'pnpm') {
    const withs = [
      ...(options.pnpmVersion ? [`version: ${options.pnpmVersion}`] : []),
      ...(options.workingDirectory
        ? [`package_json_file: ${inProject(options, 'package.json')}`]
        : []),
    ];
    steps.push(`- uses: ${uses('setupPnpm')}`);
    if (withs.length > 0) steps.push('  with:', ...withs.map((w) => `    ${w}`));
  }
  steps.push(
    `- uses: ${uses('setupNode')}`,
    '  with:',
    `    ${node}`,
    `    cache: ${options.packageManager}`,
    `    cache-dependency-path: ${lockfile}`,
    `- run: ${options.packageManager === 'pnpm' ? 'pnpm install --frozen-lockfile' : 'npm ci'}`,
    `- uses: ${uses('cache')}`,
    '  with:',
    '    path: ~/.cache/staticforge',
    `    key: staticforge-\${{ runner.os }}-\${{ hashFiles('${inProject(options, '.sforge/iac/**/.terraform.lock.hcl')}') }}`,
    '    restore-keys: staticforge-${{ runner.os }}-',
  );
  return steps.join('\n');
}

/** Sign in to the target's cloud with GitHub's OIDC token. */
function loginSteps(target: CiTarget): string {
  if (target.provider === 'aws') {
    return [
      `- uses: ${uses('awsLogin')}`,
      '  with:',
      `    role-to-assume: \${{ vars.${variable(target.name, 'ROLE_ARN')} }}`,
      `    aws-region: ${target.region ?? 'us-east-1'}`,
    ].join('\n');
  }
  return [
    `- uses: ${uses('azureLogin')}`,
    '  with:',
    `    client-id: \${{ vars.${variable(target.name, 'CLIENT_ID')} }}`,
    `    tenant-id: \${{ vars.${variable(target.name, 'TENANT_ID')} }}`,
    `    subscription-id: \${{ vars.${variable(target.name, 'SUBSCRIPTION_ID')} }}`,
  ].join('\n');
}

/** Environment variables sforge reads in a target's deploy steps. */
function targetEnv(target: CiTarget): string {
  return target.provider === 'azure'
    ? `env:\n  AZURE_SUBSCRIPTION_ID: \${{ vars.${variable(target.name, 'SUBSCRIPTION_ID')} }}\n`
    : '';
}

function defaults(options: WorkflowOptions): string {
  return options.workingDirectory === ''
    ? ''
    : `defaults:\n  run:\n    working-directory: ${options.workingDirectory}\n\n`;
}

/** Pull requests from forks get no OIDC token, so they are built and checked only. */
const SAME_REPO = 'github.event.pull_request.head.repo.full_name == github.repository';

function siteWorkflow(options: WorkflowOptions): string {
  const run = sforge(options);
  const branches = [...new Set(options.targets.map((t) => t.branch))];
  const previews = options.targets.filter((t) => t.previews);
  const sarif = inProject(options, 'sforge.sarif');

  const check = `check:
  name: Build and check
  runs-on: ubuntu-latest
  timeout-minutes: 20
  permissions:
    contents: read
    security-events: write # upload the findings to code scanning
  steps:
${indent(setupSteps(options), 4)}
    - uses: ${uses('cache')}
      with:
        path: ~/.cache/ms-playwright
        key: playwright-\${{ runner.os }}-${options.playwrightVersion}
    - name: Install Chromium for the rendered checks
      run: npx playwright-core@${options.playwrightVersion} install --with-deps --only-shell chromium
    - name: Build and check
      run: ${run} check --headless --format sarif --output sforge.sarif
    - name: Upload the findings to code scanning
      if: always() && hashFiles('${sarif}') != ''
      uses: ${uses('codeql', 'upload-sarif')}
      with:
        sarif_file: ${sarif}
        category: sforge
`;

  const previewJobs = previews.map(
    (t) => `preview-${t.name}:
  name: Preview on ${t.name}
  if: github.event_name == 'pull_request' && ${SAME_REPO}
  needs: check
  runs-on: ubuntu-latest
  timeout-minutes: 30
  permissions:
    contents: read
    id-token: write # sign in to the cloud with GitHub's OIDC token
  concurrency:
    group: sforge-${t.name}-pr-\${{ github.event.number }}
    cancel-in-progress: true
  outputs:
    url: \${{ steps.deploy.outputs.url }}
  steps:
${indent(setupSteps(options), 4)}
${indent(loginSteps(t), 4)}
    - id: deploy
      name: Deploy the preview
${indent(targetEnv(t), 6)}      run: |
        ${run} deploy ${t.name} --preview pr-\${{ github.event.number }} --no-headless --json > deploy.json
        echo "url=$(jq -r .data.url deploy.json)" >> "$GITHUB_OUTPUT"
`,
  );

  const comment =
    previews.length === 0
      ? []
      : [
          `comment:
  name: Comment the preview URLs
  if: always() && github.event_name == 'pull_request' && ${SAME_REPO}
  needs: [${previews.map((t) => `preview-${t.name}`).join(', ')}]
  runs-on: ubuntu-latest
  timeout-minutes: 5
  permissions:
    pull-requests: write
  steps:
    - name: Add or update the comment
      env:
        GH_TOKEN: \${{ github.token }}
        PR: \${{ github.event.number }}
        HEAD_SHA: \${{ github.event.pull_request.head.sha }}
${previews
  .map(
    (t) =>
      `        URL_${upper(t.name)}: \${{ needs.preview-${t.name}.outputs.url }}\n` +
      `        RESULT_${upper(t.name)}: \${{ needs.preview-${t.name}.result }}`,
  )
  .join('\n')}
      run: |
        marker='<!-- sforge-preview -->'
        body="$marker"$'\\n'"**Previews** of \${HEAD_SHA::7}:"$'\\n'
${previews
  .map(
    (t) =>
      `        body+=$'\\n'"- ${t.name}: \${URL_${upper(t.name)}:-\${RESULT_${upper(t.name)}}}"`,
  )
  .join('\n')}
        id=$(gh api "repos/$GITHUB_REPOSITORY/issues/$PR/comments" --paginate \\
          --jq ".[] | select(.body | startswith(\\"$marker\\")) | .id" | head -n 1)
        if [ -n "$id" ]; then
          gh api -X PATCH "repos/$GITHUB_REPOSITORY/issues/comments/$id" -f body="$body" > /dev/null
        else
          gh api "repos/$GITHUB_REPOSITORY/issues/$PR/comments" -f body="$body" > /dev/null
        fi
`,
        ];

  const deployJobs = options.targets.map(
    (t) => `deploy-${t.name}:
  name: Deploy ${t.name}
  if: github.event_name == 'push' && github.ref == 'refs/heads/${t.branch}'
  needs: check
  runs-on: ubuntu-latest
  timeout-minutes: 30
${
  t.environment === undefined
    ? ''
    : `  environment:
    name: ${t.environment}
    url: \${{ steps.deploy.outputs.url }}
`
}  permissions:
    contents: read
    id-token: write # sign in to the cloud with GitHub's OIDC token
  concurrency:
    group: sforge-${t.name}
    cancel-in-progress: false # concurrent deploys refuse to overwrite each other's history
  steps:
${indent(setupSteps(options), 4)}
${indent(loginSteps(t), 4)}
    - id: deploy
      name: Deploy
${indent(targetEnv(t), 6)}      run: |
        ${run} deploy ${t.name} --no-headless --json > deploy.json
        echo "url=$(jq -r .data.url deploy.json)" >> "$GITHUB_OUTPUT"
`,
  );

  return `${HEADER}name: Site

on:
  pull_request:
  push:
    branches: [${branches.join(', ')}]

permissions: {}

${defaults(options)}jobs:
${indent([check, ...previewJobs, ...comment, ...deployJobs].join('\n'), 2)}`;
}

function cleanupWorkflow(options: WorkflowOptions): string {
  const previews = options.targets.filter((t) => t.previews);
  const jobs = previews.map(
    (t) => `remove-${t.name}:
  name: Remove the preview on ${t.name}
  if: ${SAME_REPO}
  runs-on: ubuntu-latest
  timeout-minutes: 15
  permissions:
    contents: read
    id-token: write # sign in to the cloud with GitHub's OIDC token
  steps:
${indent(setupSteps(options), 4)}
${indent(loginSteps(t), 4)}
    - name: Remove the preview
${indent(targetEnv(t), 6)}      run: ${sforge(options)} preview-destroy ${t.name} pr-\${{ github.event.number }}
`,
  );
  return `${HEADER}name: Remove previews

on:
  pull_request:
    types: [closed]

permissions: {}

${defaults(options)}jobs:
${indent(jobs.join('\n'), 2)}`;
}

function rollbackWorkflow(options: WorkflowOptions): string {
  const jobs = options.targets.map(
    (t) => `rollback-${t.name}:
  name: Roll back ${t.name}
  if: inputs.target == '${t.name}'
  runs-on: ubuntu-latest
  timeout-minutes: 30
${t.environment === undefined ? '' : `  environment: ${t.environment}\n`}  permissions:
    contents: read
    id-token: write # sign in to the cloud with GitHub's OIDC token
  concurrency:
    group: sforge-${t.name}
    cancel-in-progress: false
  steps:
${indent(setupSteps(options, t.provider === 'azure' ? 0 : undefined), 4)}
${indent(loginSteps(t), 4)}
    - name: Roll back
      env:
        TO: \${{ inputs.to }}
${t.provider === 'azure' ? `        AZURE_SUBSCRIPTION_ID: \${{ vars.${variable(t.name, 'SUBSCRIPTION_ID')} }}\n` : ''}      run: ${sforge(options)} rollback ${t.name} --yes \${TO:+--to "$TO"}
`,
  );
  return `${HEADER}name: Roll back

on:
  workflow_dispatch:
    inputs:
      target:
        description: Target to roll back
        required: true
        type: choice
        options: [${options.targets.map((t) => t.name).join(', ')}]
      to:
        description: Version to serve (see \`sforge versions\`); empty for the one before the active version
        required: false
        type: string

permissions: {}

${defaults(options)}jobs:
${indent(jobs.join('\n'), 2)}`;
}

/** The workflow files, by name (no cleanup workflow when no target has previews). */
export function workflows(options: WorkflowOptions): Record<string, string> {
  return {
    'sforge.yml': siteWorkflow(options),
    ...(options.targets.some((t) => t.previews) && {
      'sforge-preview-cleanup.yml': cleanupWorkflow(options),
    }),
    'sforge-rollback.yml': rollbackWorkflow(options),
  };
}
